function getEuropeDate() {
  const formatter = new Intl.DateTimeFormat('en-CA', {
    timeZone: 'Europe/Paris',
    year: 'numeric',
    month: '2-digit',
    day: '2-digit'
  });
  return formatter.format(new Date());
}

const today = getEuropeDate();
let added = 0;
for (const pj of partnerJobs) {
  pj.postedDate = today;
  const existingIdx = existingJobs.findIndex(j => j.id === pj.id);
  if (existingIdx !== -1) {
    existingJobs[existingIdx].postedDate = today;
  } else {
    existingJobs.unshift(pj);
    existingIds.add(pj.id);
    added++;
  }
}

fs.writeFileSync(jobsFilePath, JSON.stringify(existingJobs, null, 2), 'utf-8');
console.log(`✓ Seeded ${added} curated positions from EnglishJobs.fr, Welcome to the Jungle, Apec, France Travail, Indeed, and LinkedIn into ${jobsFilePath}`);
console.log(`Total jobs in EuroPulse now: ${existingJobs.length}`);
